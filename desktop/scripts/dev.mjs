import { createServer } from 'vite';
import { build } from 'esbuild';
import { spawn, execFileSync } from 'node:child_process';
import electron from 'electron';
import { fileURLToPath } from 'node:url';
process.chdir(fileURLToPath(new URL('..', import.meta.url)));
execFileSync(process.execPath, ['node_modules/typescript/bin/tsc', '-p', 'tsconfig.node.json'], { stdio: 'inherit' });
const { displayBackend } = await import('../dist/shared/display-backend.js');
await build({ entryPoints: ['src/preload/index.ts'], outfile: 'dist/preload/index.cjs', bundle: true, platform: 'node', format: 'cjs', external: ['electron'] });
const server = await createServer();
await server.listen();
const args = process.argv.slice(2);
const display = displayBackend(process.platform, args);
if (display.relaunch) args.push(`--ozone-platform=${display.backend}`);
const child = spawn(electron, ['.', ...args], { stdio: 'inherit', env: { ...process.env, SUDO_CHAN_DEV_URL: 'http://127.0.0.1:5178' } });
const close = async () => { child.kill(); await server.close(); };
process.on('SIGINT', close);
process.on('SIGTERM', close);
child.on('exit', async code => { await server.close(); process.exit(code ?? 0); });
